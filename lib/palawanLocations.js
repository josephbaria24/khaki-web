export function municipalityCoords(name) {
  return MUNICIPALITY_COORDS[name] || null;
}

export function haversineKm(a, b) {
  if (!a || !b) return null;
  const R = 6371;
  const toRad = (deg) => (deg * Math.PI) / 180;
  const dLat = toRad(b[0] - a[0]);
  const dLon = toRad(b[1] - a[1]);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a[0])) * Math.cos(toRad(b[0])) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

// Distance between two Palawan towns, or 0 when they are the same town.
export function townDistanceKm(fromArea, toArea) {
  if (!fromArea || !toArea) return null;
  if (fromArea === toArea) return 0;
  return haversineKm(municipalityCoords(fromArea), municipalityCoords(toArea));
}

export function distanceLabel(km) {
  if (km == null) return "";
  if (km === 0) return "Same town";
  if (km < 10) return `~${km.toFixed(1)} km away`;
  return `~${Math.round(km)} km away`;
}

export function getBarangays(municipalityName) {
  const m = PALAWAN_MUNICIPALITIES.find((item) => item.name === municipalityName);
  return m ? m.barangays : [];
}

